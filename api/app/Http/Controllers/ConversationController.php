<?php

namespace App\Http\Controllers;

use App\Models\Conversation;
use App\Models\Message;
use Illuminate\Http\JsonResponse;
use Illuminate\Http\Request;
use Illuminate\Support\Str;
use Illuminate\Validation\Rule;

class ConversationController extends Controller
{
    /**
     * List the authenticated user's conversations, most recent first.
     */
    public function index(Request $request): JsonResponse
    {
        $conversations = $request->user()->conversations()
            ->latest('updated_at')
            ->limit(50)
            ->get(['id', 'title', 'pinned_at', 'created_at', 'updated_at']);

        return response()->json(['data' => $conversations]);
    }

    /**
     * Pin or unpin one of the user's conversations. Does not touch updated_at, so the order of the
     * history list stays by last activity.
     */
    public function update(Request $request, string $conversation): JsonResponse
    {
        $conversation = $this->findOwned($request, $conversation);
        abort_unless($conversation, 404);

        $data = $request->validate(['pinned' => ['required', 'boolean']]);

        $conversation->timestamps = false;
        $conversation->update(['pinned_at' => $data['pinned'] ? now() : null]);

        return response()->json(['id' => $conversation->id, 'pinned_at' => $conversation->pinned_at]);
    }

    /**
     * Return the messages of one of the user's conversations.
     */
    public function messages(Request $request, string $conversation): JsonResponse
    {
        $conversation = $this->findOwned($request, $conversation);

        $messages = $conversation
            ? $conversation->messages()->orderBy('id')->get()->map($this->present(...))
            : [];

        return response()->json(['data' => $messages]);
    }

    /**
     * Save messages into a conversation, creating the conversation on first use.
     */
    public function storeMessages(Request $request, string $conversation): JsonResponse
    {
        abort_unless(Str::isUuid($conversation), 404);

        $data = $request->validate([
            'messages' => ['required', 'array', 'min:1', 'max:20'],
            'messages.*.id' => ['required', 'string', 'max:100'],
            'messages.*.role' => ['required', 'in:user,assistant'],
            'messages.*.content' => ['nullable', 'string'],
            'messages.*.meta_data' => ['nullable', 'array'],
            // Generated by the web app from the first exchange; replaces the fallback title
            'title' => ['nullable', 'string', 'max:120'],
            // Answers the user replaced (e.g. "telaah sendiri" instead of an offered TelaahBareng post)
            'replaced_ids' => ['nullable', 'array', 'max:5'],
            'replaced_ids.*' => ['string', 'max:100'],
        ]);

        $existing = Conversation::find($conversation);

        // The id comes from the client, so it may already belong to someone else
        abort_if($existing && $existing->user_id !== $request->user()->id, 404);

        $title = isset($data['title']) ? trim($data['title']) : '';

        $conversation = $existing ?? $request->user()->conversations()->create([
            'id' => $conversation,
            'title' => $title !== '' ? $title : $this->titleFrom($data['messages']),
        ]);

        if ($existing && $title !== '') {
            $conversation->update(['title' => $title]);
        }

        if (! empty($data['replaced_ids'])) {
            $conversation->messages()->whereIn('client_id', $data['replaced_ids'])->delete();
        }

        foreach ($data['messages'] as $message) {
            $conversation->messages()->updateOrCreate(
                ['client_id' => $message['id']],
                [
                    'role' => $message['role'],
                    'content' => $message['content'] ?? null,
                    'meta_data' => $message['meta_data'] ?? null,
                ],
            );
        }

        $conversation->touch();

        return response()->json(['id' => $conversation->id], $existing ? 200 : 201);
    }

    /**
     * Delete one of the user's conversations along with its messages.
     */
    public function destroy(Request $request, string $conversation): JsonResponse
    {
        $conversation = $this->findOwned($request, $conversation);

        abort_unless($conversation, 404);

        $conversation->delete();

        return response()->json(['message' => 'Conversation deleted']);
    }

    /**
     * The user's rating of one assistant answer ("baik" or "buruk", null to withdraw it), kept
     * with the message so evaluation can read the answer it was given for.
     */
    public function feedback(Request $request, string $conversation, string $message): JsonResponse
    {
        $conversation = $this->findOwned($request, $conversation);
        $message = $conversation?->messages()->where('client_id', $message)->where('role', 'assistant')->first();
        abort_unless($message, 404);

        $data = $request->validate([
            'rating' => ['nullable', Rule::in(Message::FEEDBACK)],
            'reason' => ['nullable', 'string', 'max:500'],
        ]);
        $rating = $data['rating'] ?? null;

        // Not a new message: the history list stays ordered by the last real activity
        $message->timestamps = false;
        $message->update([
            'feedback' => $rating,
            'feedback_reason' => $rating === 'buruk' ? ($data['reason'] ?? null) : null,
            'feedback_at' => $rating ? now() : null,
        ]);

        return response()->json(['id' => $message->client_id, 'feedback' => $message->feedback]);
    }

    private function findOwned(Request $request, string $id): ?Conversation
    {
        if (! Str::isUuid($id)) {
            return null;
        }

        return $request->user()->conversations()->find($id);
    }

    /**
     * @param  array<int, array<string, mixed>>  $messages
     */
    private function titleFrom(array $messages): ?string
    {
        $firstUserMessage = collect($messages)->firstWhere('role', 'user');
        $text = trim((string) ($firstUserMessage['content'] ?? ''));

        return $text === '' ? null : Str::limit($text, 80);
    }

    /**
     * @return array<string, mixed>
     */
    private function present(Message $message): array
    {
        return [
            'id' => $message->client_id,
            'conversation_id' => $message->conversation_id,
            'role' => $message->role,
            'content' => $message->content,
            'meta_data' => $message->meta_data,
            'feedback' => $message->feedback,
            'created_at' => $message->created_at,
        ];
    }
}
